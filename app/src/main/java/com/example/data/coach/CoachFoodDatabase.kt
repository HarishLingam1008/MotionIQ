    fun findFoodMatch(query: String): FoodNutrientInfo? {
        val q = query.lowercase().trim()
        if (q.isBlank()) return null

        // 1. Direct name match
        val direct = foods.firstOrNull { food ->
            val cleanName = food.name.lowercase().substringBefore(" (").trim()
            q == cleanName || Regex("\\b${Regex.escape(cleanName)}\\b").containsMatchIn(q)
        }
        if (direct != null) return direct

        // 2. Alias match
        val aliasMatch = foods.firstOrNull { food ->
            food.aliases.any { alias ->
                val cleanAlias = alias.lowercase().trim()
                q == cleanAlias || Regex("\\b${Regex.escape(cleanAlias)}\\b").containsMatchIn(q)
            }
        }
        if (aliasMatch != null) return aliasMatch

        // 3. Partial substring match
        return foods.firstOrNull { food ->
            val cleanName = food.name.lowercase()
            cleanName.contains(q) || food.aliases.any { it.contains(q) }
        }
    }

    fun findFoodWithQuantity(query: String): Pair<FoodNutrientInfo, Double>? {
        val q = query.lowercase().trim()
        val food = findFoodMatch(q) ?: return null
        val words = q.split(" ", "-", ",")
        var quantity = 1.0

        for (w in words) {
            when (w) {
                "2", "two", "double", "pair" -> quantity = 2.0
                "3", "three", "triple" -> quantity = 3.0
                "4", "four" -> quantity = 4.0
                "5", "five" -> quantity = 5.0
                "6", "six" -> quantity = 6.0
                "half", "1/2", "0.5" -> quantity = 0.5
                "quarter", "1/4", "0.25" -> quantity = 0.25
                "one", "1", "a", "an", "single" -> quantity = 1.0
            }
            val num = w.filter { it.isDigit() }.toIntOrNull()
            if (num != null && num in 1..20 && !w.endsWith("g") && !w.endsWith("kcal") && !w.endsWith("ml") && !w.endsWith("cm") && !w.endsWith("kg")) {
                quantity = num.toDouble()
            }
        }

        return Pair(food, quantity)
    }

    fun searchFoods(query: String): List<FoodNutrientInfo> {
        val q = query.lowercase().trim()
        if (q.isBlank()) return foods
        return foods.filter { food ->
            food.name.lowercase().contains(q) ||
            food.aliases.any { it.lowercase().contains(q) } ||
            food.category.lowercase().contains(q) ||
            food.description.lowercase().contains(q)
        }
    }

    fun getAffordableProteinFoods(isVeg: Boolean = false): List<FoodNutrientInfo> {
        return foods.filter {
            it.isAffordable && (it.category == "PROTEIN" || it.proteinG >= 5.0) && (!isVeg || it.isVegetarian)
        }
    }

    fun getFoodsForMeal(meal: String, isVeg: Boolean = false): List<FoodNutrientInfo> {
        return foods.filter {
            it.mealSuitability.contains(meal.uppercase()) && (!isVeg || it.isVegetarian)
        }
    }

    fun getFoodsByCategory(category: String, isVeg: Boolean = false): List<FoodNutrientInfo> {
        return foods.filter {
            it.category.equals(category, ignoreCase = true) && (!isVeg || it.isVegetarian)
        }
    }
